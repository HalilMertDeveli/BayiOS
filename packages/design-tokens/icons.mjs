#!/usr/bin/env node
/**
 * BayiOS icon set (#222) — imports the UI kit SVGs once and writes both platforms' copies.
 *
 * Input:  a folder of the kit's 24×24 SVGs (argument; the owner's asset pack `ikonlar/`).
 * Output: packages/design-tokens/icons/<name>.svg      normalised source of truth (monochrome → currentColor)
 *         apps/mobile/assets/icons/<name>.svg          same files, for flutter_svg (AppIcon tints them)
 *         apps/web/src/components/ui/icons/data.ts     element trees for the React <AppIcon> (no raw HTML sink)
 *
 * Monochrome kit icons draw with the kit grey (#707371); it becomes `currentColor` so the icon takes the text colour.
 * Multi-colour icons (sun, WhatsApp) keep their colours ("multicolor"); raster-based kit illustrations are skipped.
 * Third-party marketplace/brand logos are not shipped (owner: no Amazon/eBay/AliExpress; the rest are unused trademarks).
 *
 * Usage: node packages/design-tokens/icons.mjs <kit-icon-folder>
 *        node packages/design-tokens/icons.mjs            (re-generate from packages/design-tokens/icons)
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const sourceDir = resolve(here, "icons");
const input = process.argv[2] ? resolve(process.argv[2]) : sourceDir;

const EXCLUDED = new Set([
  "aliexpress_logomark",
  "amazonlogomark",
  "ebay_logomark",
  "etsy_logomark",
  "facebook_logomark",
  "google_logomark",
  "mailchimp",
  "microsoft",
  "salesforce",
  "shopify",
  "slack_logomark",
  "icon", // a third-party product mark in the kit
  // Raster illustrations (embedded PNG patterns), not vectors — not shipped.
  "folder",
  "folder_1",
  "inbox_2",
  "picture_1",
  "upload_1",
  "upload_2",
  "upload_3",
]);
const MULTICOLOR = new Set(["sun_03", "whatsapp_logomark"]);
const KIT_GREY = /#707371/gi;

mkdirSync(sourceDir, { recursive: true });
const mobileDir = resolve(root, "apps/mobile/assets/icons");
mkdirSync(mobileDir, { recursive: true });

const names = [];
for (const file of readdirSync(input).filter((f) => f.endsWith(".svg")).sort()) {
  const name = basename(file, ".svg");
  if (EXCLUDED.has(name)) continue;
  let svg = readFileSync(resolve(input, file), "utf8").replace(/\r\n/g, "\n");
  if (!MULTICOLOR.has(name)) svg = svg.replace(KIT_GREY, "currentColor");
  if (input !== sourceDir) writeFileSync(resolve(sourceDir, file), svg);
  copyFileSync(resolve(sourceDir, file), resolve(mobileDir, file));
  names.push(name);
}

/** Minimal SVG → element tree (the kit files are flat: <svg> with path/circle/rect/g/defs children). */
function parse(svg) {
  const tokens = svg.match(/<\/?[a-zA-Z][^>]*>/g) ?? [];
  const rootNode = { tag: "root", attrs: {}, children: [] };
  const stack = [rootNode];
  for (const t of tokens) {
    if (t.startsWith("</")) {
      stack.pop();
      continue;
    }
    const tag = /^<([a-zA-Z][\w:-]*)/.exec(t)[1];
    const attrs = {};
    for (const m of t.matchAll(/([a-zA-Z_:][\w:.-]*)="([^"]*)"/g)) {
      const key = m[1]
        .replace(/^xlink:href$/, "href")
        .replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      if (key === "xmlns" || key.startsWith("xmlns:")) continue;
      attrs[key] = m[2];
    }
    const node = { tag, attrs, children: [] };
    stack[stack.length - 1].children.push(node);
    if (!t.endsWith("/>")) stack.push(node);
  }
  return rootNode.children[0];
}

const entries = names.map((name) => {
  const svg = parse(readFileSync(resolve(sourceDir, `${name}.svg`), "utf8"));
  const compact = (n) => [n.tag, n.attrs, ...(n.children.length ? [n.children.map(compact)] : [])];
  return `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(svg.attrs.viewBox ?? "0 0 24 24")}, multicolor: ${MULTICOLOR.has(name)}, nodes: ${JSON.stringify(svg.children.map(compact))} },`;
});

const ts = `/* Generated by packages/design-tokens/icons.mjs — do not edit by hand.
 * Icons: "AI Inventory Management Web App UI Kit" — Lukáš Marek (Figma Community), CC BY 4.0; modified (currentColor). */

/** [tag, attributes, children?] — rendered with React.createElement, never as raw HTML. */
export type IconNode = [string, Record<string, string>, IconNode[]?];
export type IconData = { viewBox: string; multicolor: boolean; nodes: IconNode[] };

export const ICONS = {
${entries.join("\n")}
} as const satisfies Record<string, IconData>;

export type IconName = keyof typeof ICONS;
`;
writeFileSync(resolve(root, "apps/web/src/components/ui/icons/data.ts"), ts);
console.log(`${names.length} icons → packages/design-tokens/icons, apps/mobile/assets/icons, apps/web/src/components/ui/icons/data.ts`);
