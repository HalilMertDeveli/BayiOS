#!/usr/bin/env node
/**
 * BayiOS design tokens — single source (#222).
 *
 * Input:  packages/design-tokens/renkler.json, tipografi.json (exported from the UI kit
 *         "AI Inventory Management Web App UI Kit" — Lukáš Marek, Figma Community, CC BY 4.0; modified).
 * Output: apps/web/src/app/tokens.css                     raw palette, spacing, radius, type scale as CSS custom properties
 *         apps/mobile/lib/core/theme/app_palette.dart     the same raw values for Flutter
 *
 * The semantic layer (text/surface/border/tone, light + dark, WCAG-checked) is written by hand on top of these raw
 * values: web `apps/web/src/app/globals.css`, mobile `apps/mobile/lib/core/theme/app_colors.dart`.
 *
 * Usage: node packages/design-tokens/build.mjs [--check]   (--check exits 1 when a generated file is stale)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const colors = JSON.parse(readFileSync(resolve(here, "renkler.json"), "utf8"));
const typography = JSON.parse(readFileSync(resolve(here, "tipografi.json"), "utf8"));

const HEADER = "Generated by packages/design-tokens/build.mjs from renkler.json + tipografi.json — do not edit by hand.";
const CREDIT =
  "Source: \"AI Inventory Management Web App UI Kit\" — Lukáš Marek (Figma Community), CC BY 4.0; modified for BayiOS.";

/** Raw palette families we ship. Alpha families are derived on the fly where needed (dark cards). */
const FAMILIES = {
  Primary: "primary",
  Grayscale: "gray",
  Success: "green",
  Red: "red",
  Yellow: "yellow",
  Blue: "blue",
  Purple: "purple",
};

const palette = [];
for (const [key, hex] of Object.entries(colors.Foundations["Mode 1"])) {
  const [family, step] = key.split("/");
  if (FAMILIES[family]) palette.push({ family: FAMILIES[family], step, hex: hex.toLowerCase() });
}
palette.push({ family: "white", step: "", hex: "#ffffff" }, { family: "black", step: "", hex: "#000000" });

const global = colors.Global["Mode 1"];
const spacing = Object.entries(global)
  .filter(([k]) => k.startsWith("Padding/"))
  .map(([k, v]) => ({ name: k.slice("Padding/".length), px: v }));
const radius = Object.entries(global)
  .filter(([k]) => k.startsWith("Radius/"))
  .map(([k, v]) => ({ name: k.slice("Radius/".length), px: v }));

const WEIGHTS = { Regular: 400, Medium: 500, SemiBold: 600, Bold: 700 };
const slug = (name) =>
  name
    .replace("X-Samll", "XSmall") // typo in the kit export
    .replace(/[^A-Za-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .toLowerCase();
const type = typography.map((t) => ({
  name: slug(t.name),
  size: t.size,
  lineHeight: parseInt(t.lineHeight, 10),
  weight: WEIGHTS[t.style] ?? 400,
}));

const cssVar = (p) => `--bos-${p.family}${p.step ? `-${p.step}` : ""}`;

function css() {
  const lines = [`/* ${HEADER}`, ` * ${CREDIT} */`, "", ":root {"];
  lines.push("  /* palette (theme-independent; components use the semantic tokens in globals.css) */");
  for (const p of palette) lines.push(`  ${cssVar(p)}: ${p.hex};`);
  lines.push("", "  /* spacing (Padding/*) */");
  for (const s of spacing) lines.push(`  --bos-space-${s.name}: ${s.px}px;`);
  lines.push("", "  /* radius (Radius/*) */");
  for (const r of radius) lines.push(`  --bos-radius-${r.name}: ${r.px}px;`);
  lines.push("", "  /* type scale (size / line height / weight) */");
  for (const t of type) {
    lines.push(`  --bos-type-${t.name}-size: ${t.size / 16}rem;`);
    lines.push(`  --bos-type-${t.name}-line: ${t.lineHeight / 16}rem;`);
    lines.push(`  --bos-type-${t.name}-weight: ${t.weight};`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const dartHex = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;
const dartNum = (n) => (Number.isInteger(n) ? `${n}` : `${n}`);
const dartIdent = (s) => (/^\d/.test(s) ? `x${s}` : s);

function dart() {
  const lines = [
    `// ${HEADER}`,
    `// ${CREDIT}`,
    "",
    "import 'package:flutter/painting.dart';",
    "",
    "/// Raw kit palette. Screens never use it directly — only `AppColors` (theme",
    "/// extension, light + dark) and the Material `ColorScheme` built from it.",
    "abstract final class AppPalette {",
  ];
  for (const p of palette) lines.push(`  static const ${camel(`${p.family}${p.step ? `-${p.step}` : ""}`)} = ${dartHex(p.hex)};`);
  lines.push("}", "", "/// Spacing scale (Padding/*), logical pixels.", "abstract final class AppSpacingScale {");
  for (const s of spacing) lines.push(`  static const double ${dartIdent(camel(s.name))} = ${dartNum(s.px)};`);
  lines.push("}", "", "/// Radius scale (Radius/*), logical pixels.", "abstract final class AppRadiusScale {");
  for (const r of radius) lines.push(`  static const double ${dartIdent(camel(r.name))} = ${dartNum(r.px)};`);
  lines.push("}", "", "/// Type scale: font size, line height (px) and weight per kit text style.", "abstract final class AppTypeScale {");
  for (const t of type) {
    const n = camel(t.name);
    lines.push(`  static const double ${n}Size = ${dartNum(t.size)};`);
    lines.push(`  static const double ${n}Line = ${dartNum(t.lineHeight)};`);
    lines.push(`  static const FontWeight ${n}Weight = FontWeight.w${t.weight};`);
  }
  lines.push("}", "");
  return lines.join("\n");
}

const outputs = [
  [resolve(root, "apps/web/src/app/tokens.css"), css()],
  [resolve(root, "apps/mobile/lib/core/theme/app_palette.dart"), dart()],
];

const check = process.argv.includes("--check");
let stale = false;
for (const [file, content] of outputs) {
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {
    /* missing → stale */
  }
  if (current.replace(/\r\n/g, "\n") === content) continue;
  if (check) {
    console.error(`stale: ${file}`);
    stale = true;
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${file}`);
  }
}
if (stale) process.exit(1);
