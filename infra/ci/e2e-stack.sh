#!/usr/bin/env bash
# Real-stack E2E environment (issue #40). Used by .github/workflows/e2e-real.yml and runnable locally from the repo root
# (needs bash, Docker, the .NET SDK, Node 24):
#
#   bash infra/ci/e2e-stack.sh up      # Supabase Auth (CLI, ES256) + Postgres 17 + EF migrations + API + web (prod build)
#   npm --prefix apps/web run test:e2e:real
#   bash infra/ci/e2e-stack.sh down
#
# Nothing is mocked:
#   - Auth: the Supabase CLI local stack (GoTrue + Kong gateway + Mailpit) signing ES256 tokens; the API validates them
#     against its JWKS exactly like production. Only config differs (http issuer => Auth__RequireHttpsMetadata=false).
#   - Data: a separate empty postgres:17 bootstrapped with infra/docker/initdb; schema = the idempotent EF scripts
#     generated by infra/ci/ef-migrations.sh, applied as bayios_migrator; the API connects as bayios_app (NOBYPASSRLS).
#   - API: Release publish, ASPNETCORE_ENVIRONMENT=Production. Web: `next build` + `next start`.
#
# No secrets: every password is generated here per run (or a local-only default) and never leaves the machine. The
# Supabase keys printed by the CLI are the public, well-known local-development keys.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
STATE_DIR="${E2E_STATE_DIR:-${RUNNER_TEMP:-${TMPDIR:-/tmp}}/bayios-e2e}"
SUPABASE_CLI="${SUPABASE_CLI:-supabase@2.122.1}"
SUPABASE_WORKDIR="${REPO_ROOT}/infra/supabase/local"
PG_IMAGE="${PG_IMAGE:-postgres:17}"
PG_CONTAINER="${E2E_PG_CONTAINER:-bayios-e2e-postgres}"
PG_PORT="${E2E_PG_PORT:-55432}"
API_PORT="${E2E_API_PORT:-5280}"
WEB_PORT="${E2E_WEB_PORT:-3200}"
SUPABASE_URL="http://127.0.0.1:54321"
# Only the Auth path of the Supabase stack is needed: db (GoTrue's own store), gotrue, kong, mailpit.
SUPABASE_EXCLUDE="studio,postgrest,postgres-meta,storage-api,realtime,edge-runtime,logflare,vector,supavisor,imgproxy"

log() { printf '\n==> [%s] %s\n' "$(date -u +%H:%M:%S)" "$*"; }
fail() { printf '::error::%s\n' "$*" >&2; exit 1; }
native_path() { if command -v cygpath >/dev/null 2>&1; then cygpath -w "$1"; else printf '%s' "$1"; fi; }
supabase() { npx -y "$SUPABASE_CLI" "$@" --workdir "$SUPABASE_WORKDIR"; }
random_password() { od -An -N18 -tx1 /dev/urandom | tr -d ' \n'; }

wait_http() { # url, seconds, label
  local url="$1" seconds="$2" label="$3"
  for _ in $(seq 1 "$seconds"); do
    if curl --silent --fail --max-time 5 -o /dev/null "$url"; then return 0; fi
    sleep 1
  done
  return 1
}

start_bg() { # name, log file, command...
  local name="$1" logfile="$2"; shift 2
  nohup "$@" >"$logfile" 2>&1 &
  echo $! >"${STATE_DIR}/${name}.pid"
}

stop_bg() {
  local pidfile="${STATE_DIR}/$1.pid"
  [ -f "$pidfile" ] || return 0
  kill "$(cat "$pidfile")" >/dev/null 2>&1 || true
  rm -f "$pidfile"
}

# ---------------------------------------------------------------- 1. Supabase Auth (ES256)
up_supabase() {
  local keys="${SUPABASE_WORKDIR}/supabase/signing_keys.json"
  if [ ! -s "$keys" ] || ! grep -q '"kty"' "$keys"; then
    log "Generating a throwaway ES256 signing key (git-ignored)"
    echo "[]" >"$keys" # CLI 2.122.1 expects an existing JSON array
    supabase gen signing-key --algorithm ES256 --yes >/dev/null
  fi
  log "Starting Supabase Auth (excluded: ${SUPABASE_EXCLUDE})"
  supabase start -x "$SUPABASE_EXCLUDE"
  local status
  status="$(supabase status -o json 2>/dev/null)"
  PUBLISHABLE_KEY="$(printf '%s' "$status" | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{const j=JSON.parse(s.slice(s.indexOf("{")));process.stdout.write(j.PUBLISHABLE_KEY||j.ANON_KEY)})')"
  [ -n "$PUBLISHABLE_KEY" ] || fail "Could not read the publishable key from 'supabase status'"
  wait_http "${SUPABASE_URL}/auth/v1/.well-known/jwks.json" 60 jwks || fail "Supabase JWKS not reachable"
  curl --silent --fail "${SUPABASE_URL}/auth/v1/.well-known/jwks.json" | grep -q '"ES256"' \
    || fail "Supabase JWKS does not publish an ES256 key (the API rejects HS256 by design)"
}

# ---------------------------------------------------------------- 2. Postgres 17 + EF migrations
up_database() {
  local scripts="${STATE_DIR}/migrations"
  if [ "${E2E_REUSE_MIGRATIONS:-0}" = 1 ] && ls "${scripts}"/*.sql >/dev/null 2>&1; then
    log "Reusing migration scripts in ${scripts}"
  else
    log "Generating idempotent EF migration scripts (infra/ci/ef-migrations.sh)"
    OUT_DIR="$scripts" PG_CONTAINER="${PG_CONTAINER}-check" bash "${REPO_ROOT}/infra/ci/ef-migrations.sh"
  fi

  log "Starting ${PG_IMAGE} on 127.0.0.1:${PG_PORT}"
  docker rm -f "$PG_CONTAINER" >/dev/null 2>&1 || true
  MSYS_NO_PATHCONV=1 docker run -d --name "$PG_CONTAINER" -p "127.0.0.1:${PG_PORT}:5432" \
    -e POSTGRES_DB=bayios -e POSTGRES_USER=postgres -e POSTGRES_PASSWORD="$(random_password)" \
    -e BAYIOS_APP_PASSWORD="$APP_PASSWORD" -e BAYIOS_MIGRATOR_PASSWORD="$MIGRATOR_PASSWORD" \
    -v "$(native_path "${REPO_ROOT}/infra/docker/initdb"):/docker-entrypoint-initdb.d:ro" \
    "$PG_IMAGE" >/dev/null
  local ready=0
  for _ in $(seq 1 60); do
    if docker exec "$PG_CONTAINER" pg_isready -h 127.0.0.1 -U postgres -d bayios >/dev/null 2>&1; then ready=1; break; fi
    sleep 1
  done
  [ "$ready" = 1 ] || { docker logs "$PG_CONTAINER"; fail "postgres did not become ready"; }

  # Same order as ef-migrations.sh (sorted module paths), which CI proves applies cleanly to an empty database.
  for script in "${scripts}"/*.sql; do
    log "Apply $(basename "$script") as bayios_migrator"
    MSYS_NO_PATHCONV=1 docker exec -i -e PGPASSWORD="$MIGRATOR_PASSWORD" "$PG_CONTAINER" \
      psql -h 127.0.0.1 -U bayios_migrator -d bayios -v ON_ERROR_STOP=1 -q -f - <"$script" >/dev/null
  done
}

# ---------------------------------------------------------------- 3. API (Release publish, Production environment)
up_api() {
  local out="${STATE_DIR}/api"
  log "Publishing the API (Release)"
  dotnet publish "${REPO_ROOT}/services/api/src/BayiOS.Api/BayiOS.Api.csproj" -c Release -o "$out" -nologo -v quiet
  rm -f "${out}/appsettings.Development.json"

  log "Starting the API on http://localhost:${API_PORT}"
  stop_bg api
  ASPNETCORE_ENVIRONMENT=Production \
  ASPNETCORE_URLS="http://127.0.0.1:${API_PORT}" \
  ConnectionStrings__Default="Host=127.0.0.1;Port=${PG_PORT};Database=bayios;Username=bayios_app;Password=${APP_PASSWORD}" \
  Auth__Authority="${SUPABASE_URL}/auth/v1" \
  Auth__Audience=authenticated \
  Auth__RequireHttpsMetadata=false \
  Cors__AllowedOrigins__0="http://localhost:${WEB_PORT}" \
    start_bg api "${STATE_DIR}/api.log" dotnet "${out}/BayiOS.Api.dll"
  if ! wait_http "http://127.0.0.1:${API_PORT}/health/ready" 60 api; then
    cat "${STATE_DIR}/api.log"
    fail "API did not become ready (GET /health/ready)"
  fi
}

# ---------------------------------------------------------------- 4. Web (production build)
up_web() {
  local web="${REPO_ROOT}/apps/web"
  export NEXT_PUBLIC_API_BASE_URL="http://localhost:${API_PORT}"
  export NEXT_PUBLIC_SUPABASE_URL="$SUPABASE_URL"
  export NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY="$PUBLISHABLE_KEY"
  if [ "${E2E_SKIP_WEB_BUILD:-0}" != 1 ]; then
    log "Building the web app (next build)"
    [ -d "${web}/node_modules" ] || npm --prefix "$web" ci
    npm --prefix "$web" run build
  fi
  log "Starting the web app on http://localhost:${WEB_PORT}"
  stop_bg web
  # node directly (not `npm run start`): the recorded PID is the server itself, so `down` stops it on every OS.
  start_bg web "${STATE_DIR}/web.log" node "${web}/node_modules/next/dist/bin/next" start "$web" -p "$WEB_PORT"
  if ! wait_http "http://localhost:${WEB_PORT}/giris" 60 web; then
    cat "${STATE_DIR}/web.log"
    fail "web app did not start"
  fi
}

up() {
  mkdir -p "$STATE_DIR"
  APP_PASSWORD="${BAYIOS_APP_PASSWORD:-$(random_password)}"
  MIGRATOR_PASSWORD="${BAYIOS_MIGRATOR_PASSWORD:-$(random_password)}"
  up_supabase
  up_database
  up_api
  up_web
  log "Stack ready: web http://localhost:${WEB_PORT} · API http://localhost:${API_PORT} · Auth ${SUPABASE_URL} · Mailpit http://127.0.0.1:54324"
  log "Logs: ${STATE_DIR}/api.log, ${STATE_DIR}/web.log"
}

down() {
  stop_bg web
  stop_bg api
  docker rm -f "$PG_CONTAINER" >/dev/null 2>&1 || true
  # CI: drop the throwaway Auth volume. Locally keep it (your local users) unless E2E_SUPABASE_NO_BACKUP=1.
  if [ "${CI:-}" = true ] || [ "${E2E_SUPABASE_NO_BACKUP:-0}" = 1 ]; then
    supabase stop --no-backup || true
  else
    supabase stop || true
  fi
}

case "${1:-}" in
  up) up ;;
  down) down ;;
  *) echo "usage: $0 up|down" >&2; exit 2 ;;
esac
